/**
 * Builds every published artifact from the curated source documents.
 *
 * This is the only entry point in the project that turns `data/sources/` into
 * `apps/web/public/data/`. It runs as part of `pnpm run build`, before the site
 * is bundled, because Vite copies `public/` at build time -- a site built
 * without this step is a site whose every tool reports that its data has not
 * been published, which is a real state with a real message and exactly the
 * wrong thing to ship by accident.
 *
 * Everything with a decision in it lives elsewhere: the source adapters decide
 * what the data means, `planPublication` decides what files exist and what they
 * are called, and `writePublication` writes them. What is left here is
 * discovery, ordering, and the output directory.
 *
 * USAGE
 *
 *   node packages/ingestion/dist/bin/publish-data.js [--dry-run]
 *
 * Run from the repository root; both directories are resolved against the
 * working directory. `--dry-run` plans and validates without writing, which is
 * what makes a typo in a transcription a failed build rather than a wrong
 * number on a lifter's screen.
 */
import { createHash } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { readFile, readdir, rm, stat } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import process from 'node:process';
import { createInterface } from 'node:readline';

import {
  ATHLETE_MIRROR_ARTIFACT_ID,
  AthleteMirrorInfoSchema,
  CategoryCatalogSchema,
  ConversionChartSchema,
  MEET_RULES_ARTIFACT_ID,
  MeetRuleBookSchema,
  categoryCatalogArtifactId,
  conversionChartArtifactId,
  type CategoryCatalog,
  type SourceFreshness,
} from '@platform-toolkit/data-contracts';

import { planPublication, type ArtifactSource } from '../publication.js';
import { shardAthleteMirror } from '../shard-athletes.js';
import { shardClassificationBook } from '../shard-classifications.js';
import { shardRecordBook } from '../shard-records.js';
import { buildAthleteMirror, summarizeWithheld } from '../sources/athlete-mirror.js';
import { buildCategoryCatalog } from '../sources/category-catalog.js';
import {
  buildClassificationTables,
  readClassificationSourceReferences,
} from '../sources/classification-standards.js';
import { buildConversionChart } from '../sources/conversion-chart.js';
import { buildMeetRuleBook } from '../sources/meet-rules.js';
import { buildRecordBook, readRecordSourceReferences } from '../sources/records.js';
import { writePublication } from '../write-publication.js';

/**
 * Curated documents, one directory per kind.
 *
 * The directory is the discriminator. A `kind` field inside each document would
 * do the same job and would then have to be kept honest by a check; a file's
 * location cannot be wrong about itself, and a new kind of source is a new
 * directory and a new branch below rather than a schema change.
 */
const SOURCE_ROOT = 'data/sources';
const CATEGORY_SOURCES = join(SOURCE_ROOT, 'categories');
const CLASSIFICATION_SOURCES = join(SOURCE_ROOT, 'classifications');
const CONVERSION_SOURCES = join(SOURCE_ROOT, 'conversions');
const MEET_RULE_SOURCES = join(SOURCE_ROOT, 'meet-rules');
const RECORD_SOURCES = join(SOURCE_ROOT, 'records');
const ATHLETE_SOURCES = join(SOURCE_ROOT, 'athletes');

/**
 * The environment variable that turns the results archive on.
 *
 * Every other source in this script publishes from a document in the repository,
 * so a checkout is enough to reproduce a build. This one cannot work that way:
 * the archive is 816 MB of CSV rebuilt upstream every week, far too large to
 * commit and pointless to pin. It is downloaded to a gitignored `.cache/` and
 * this variable names the extracted file.
 *
 * Unset means publish nothing and say so in one line. That is the default on
 * purpose and it is not a stub -- a build without the archive is a complete site
 * whose lookup screen honestly reports that no archive was published, which is a
 * state `getAthleteMirror` exists to express. Turning it on in CI is one variable
 * and roughly 217 MB of published output, which is a decision with a person
 * behind it rather than a consequence of merging this file.
 */
const CORPUS_VARIABLE = 'PTK_ATHLETE_CORPUS';

/**
 * Where a classification mapping's committed upstream dataset lives.
 *
 * A subdirectory rather than a sibling, because `readSourceDocuments` reads every
 * `.json` file in a source directory and a snapshot is not a mapping. Nesting it
 * keeps the two apart without a naming convention that a new file could miss.
 */
const SNAPSHOT_DIRECTORY = 'snapshots';

/** Where the site expects to find them. Gitignored; regenerated by every build. */
const OUTPUT_DIRECTORY = join('apps', 'web', 'public', 'data');

/** Contract version carried into the index for every artifact this script emits. */
const SCHEMA_VERSION = 1;

/**
 * The one file the output directory is allowed to contain besides `artifacts/`.
 *
 * Checked before anything is deleted. This script clears its output so that
 * `writePublication` can keep refusing to overwrite -- which is what catches two
 * artifacts colliding on a name -- and a directory that turned out to hold
 * something else would mean the path is wrong, not that the contents are stale.
 */
const EXPECTED_OUTPUT_ENTRIES = new Set(['meta.json', 'artifacts']);

async function main(): Promise<void> {
  const dryRun = process.argv.includes('--dry-run');
  const generatedAt = readGeneratedAt();

  const artifacts: ArtifactSource<unknown>[] = [];
  const sources: SourceFreshness[] = [];

  // Catalogues first, and kept, because everything below is checked against one.
  // A classification table naming a weight class the rulebook does not define is
  // a table no lookup will ever match, which on screen is indistinguishable from
  // a category the federation publishes no standards for.
  const catalogs = new Map<string, CategoryCatalog>();

  for (const document of await readSourceDocuments(CATEGORY_SOURCES)) {
    const { catalog, freshness } = buildCategoryCatalog(document.value);
    const id = categoryCatalogArtifactId(catalog.id);
    if (id === null) {
      // The federation identifier slugged away to nothing, so there is no
      // filename to publish it under. Total on the browser side, because "no
      // such artifact" is renderable there; here it is a bad document.
      throw new Error(
        `${document.path}: federation identifier "${catalog.id}" cannot be used in a filename.`,
      );
    }
    if (catalogs.has(catalog.id)) {
      throw new Error(`${document.path}: a second catalogue claims federation "${catalog.id}".`);
    }
    catalogs.set(catalog.id, catalog);
    artifacts.push({
      id,
      schema: CategoryCatalogSchema,
      schemaVersion: SCHEMA_VERSION,
      value: catalog,
    });
    sources.push(freshness);
  }

  for (const document of await readSourceDocuments(CLASSIFICATION_SOURCES)) {
    const { federationId, standardsFile } = readClassificationSourceReferences(document.value);
    const catalog = catalogs.get(federationId);
    if (catalog === undefined) {
      throw new Error(
        `${document.path}: no category catalogue is published for federation "${federationId}".`,
      );
    }

    const snapshot = await readSnapshot(
      join(CLASSIFICATION_SOURCES, SNAPSHOT_DIRECTORY),
      standardsFile,
    );
    const { tables, freshness, withheld } = buildClassificationTables(
      document.value,
      snapshot,
      catalog,
    );

    for (const shard of shardClassificationBook(
      { id: federationId, label: catalog.label, tables: [...tables] },
      catalog.equipment.map((entry) => entry.id),
      SCHEMA_VERSION,
    )) {
      artifacts.push(shard);
    }
    sources.push(freshness);

    // Said out loud rather than left to the diff. A withheld row is a category a
    // lifter will find empty, and the number going up is the signal that upstream
    // has published something new that contradicts itself.
    if (withheld.length > 0) {
      console.log(
        `${document.path}: withheld ${String(withheld.length)} published rows:\n  ` +
          withheld.map((entry) => `${entry.row} -- ${entry.reason}`).join('\n  '),
      );
    }
  }

  for (const document of await readSourceDocuments(RECORD_SOURCES)) {
    const { federationId, snapshotFile } = readRecordSourceReferences(document.value);
    const catalog = catalogs.get(federationId);
    if (catalog === undefined) {
      throw new Error(
        `${document.path}: no category catalogue is published for federation "${federationId}".`,
      );
    }

    const snapshot = await readRecordSnapshot(
      join(RECORD_SOURCES, SNAPSHOT_DIRECTORY),
      snapshotFile,
    );
    const { book, freshness, withheld } = buildRecordBook(document.value, snapshot, catalog);

    // One artifact per (level, region, sex, equipment). The whole corpus is
    // hundreds of megabytes; a lifter's screen needs one of these files.
    let published = 0;
    let partitions = 0;
    for (const shard of shardRecordBook(book, SCHEMA_VERSION)) {
      artifacts.push(shard);
      published += shard.recordCount;
      partitions += 1;
    }
    sources.push(freshness);

    // Counted out loud, because the two numbers that matter here are not visible
    // in a diff: how much of the corpus survived, and how many files a deploy
    // now carries. A refresh that halves either is the signal to look upstream.
    console.log(
      `${document.path}: published ${String(published)} records in ` +
        `${String(partitions)} partitions, withheld ${String(withheld.length)} rows.`,
    );

    // Grouped rather than listed. Withheld rows here run to the hundreds and
    // arrive in families -- a class one ladder does not have, a lift a discipline
    // does not contest -- so a full list buries every other line of the build.
    // Row keys name a position and never a holder (section 2.3), but they are
    // still not what a reader needs; the count per rule is.
    const byReason = new Map<string, number>();
    for (const row of withheld) {
      byReason.set(row.reason, (byReason.get(row.reason) ?? 0) + 1);
    }
    for (const [reason, count] of [...byReason].sort(([, left], [, right]) => right - left)) {
      console.log(`  ${String(count)} x ${reason}`);
    }
  }

  // Conversion charts stand alone deliberately: a converter is useful to a lifter
  // in a federation this project has never transcribed a rulebook for, and
  // requiring a category catalogue alongside would make the smallest tool depend
  // on the largest dataset.
  for (const document of await readSourceDocuments(CONVERSION_SOURCES)) {
    const { chart, freshness, anomalies } = buildConversionChart(document.value);
    const id = conversionChartArtifactId(chart.id);
    if (id === null) {
      throw new Error(
        `${document.path}: federation identifier "${chart.id}" cannot be used in a filename.`,
      );
    }
    artifacts.push({
      id,
      schema: ConversionChartSchema,
      schemaVersion: SCHEMA_VERSION,
      value: chart,
    });
    sources.push(freshness);

    // Printed, not thrown. A row the chart's own factor does not reproduce is
    // still the row the meet runs on; what it needs is somebody's eyes, not a
    // failed build. See the note in the adapter.
    if (anomalies.length > 0) {
      console.log(
        `${document.path}: ${String(anomalies.length)} row(s) disagree with the chart's printed factor:\n  ` +
          anomalies
            .map(
              (anomaly) =>
                `${String(anomaly.kilograms)} kg: chart says ${String(anomaly.publishedPounds)} lb, ` +
                `the factor gives ${String(anomaly.factorPounds)} lb`,
            )
            .join('\n  '),
      );
    }
  }

  // Every federation's rules in one artifact, and one adapter call rather than a
  // loop, because the two checks worth having here are between documents: a
  // duplicated federation id, and a book with nothing in it. See the adapter.
  //
  // Unlike everything above, the artifact id is a constant rather than a name
  // derived from a federation -- there is one book, and the planner's first
  // question is which profile in it applies, which it cannot ask without the
  // whole list in hand.
  const meetRuleDocuments = await readSourceDocuments(MEET_RULE_SOURCES);
  const { book, freshness: meetRuleFreshness } = buildMeetRuleBook(
    meetRuleDocuments.map((document) => document.value),
  );
  artifacts.push({
    id: MEET_RULES_ARTIFACT_ID,
    schema: MeetRuleBookSchema,
    schemaVersion: SCHEMA_VERSION,
    value: book,
  });
  sources.push(...meetRuleFreshness);

  await publishAthleteMirror(artifacts, sources);

  if (artifacts.length === 0) {
    // Publishing an empty index would replace a working site's data with a
    // valid document describing nothing, and every tool would report that its
    // data has not been published. Loud is better.
    throw new Error(`No source documents found under ${SOURCE_ROOT}.`);
  }

  const plan = planPublication({ generatedAt, sources, artifacts });

  if (dryRun) {
    console.log(
      `Planned ${String(plan.files.length)} files from ${String(artifacts.length)} artifacts. Nothing written.`,
    );
    return;
  }

  const directory = resolve(process.cwd(), OUTPUT_DIRECTORY);
  await clearOutputDirectory(directory);
  const summary = await writePublication(plan, directory);
  console.log(
    `Published ${String(summary.fileCount)} files (${String(summary.totalBytes)} bytes) to ${OUTPUT_DIRECTORY}.`,
  );
}

/**
 * Publishes the results archive, if this build was pointed at one.
 *
 * Its own function rather than another block in `main`, because it is the one
 * source that can be absent by design and the early return is the whole point.
 *
 * The archive is streamed twice and never held: `openRows` opens a fresh reader
 * each time it is called, so the adapter can learn who is in scope on one pass
 * and project them on the next without four million entries in memory. See the
 * adapter's header for why one pass cannot do it.
 */
async function publishAthleteMirror(
  artifacts: ArtifactSource<unknown>[],
  sources: SourceFreshness[],
): Promise<void> {
  const corpusPath = process.env[CORPUS_VARIABLE];
  if (corpusPath === undefined || corpusPath === '') {
    console.log(
      `${CORPUS_VARIABLE} is unset; publishing no results archive. The lookup screen ` +
        'will report that this build has none, which is a supported state.',
    );
    return;
  }

  const corpus = resolve(process.cwd(), corpusPath);
  // Checked before the documents are read, so a mistyped path fails on the path
  // rather than a hundred lines later inside a stream, where the error arrives
  // as a failed read of something the message does not name.
  const stats = await stat(corpus).catch((cause: unknown) => {
    throw new Error(`${CORPUS_VARIABLE} names ${corpusPath}, which cannot be read.`, { cause });
  });
  if (!stats.isFile()) {
    throw new Error(`${CORPUS_VARIABLE} names ${corpusPath}, which is not a file.`);
  }

  const documents = await readSourceDocuments(ATHLETE_SOURCES);
  const [document, ...extra] = documents;
  if (document === undefined) {
    throw new Error(
      `${CORPUS_VARIABLE} is set but ${ATHLETE_SOURCES} holds no document saying what to ` +
        'mirror out of it. The scope is data, never a default (section 5.1).',
    );
  }
  if (extra.length > 0) {
    // One archive, one scope. Two documents would each mirror an overlapping set
    // of lifters into the same buckets, and the sharder would refuse the
    // duplicate -- correctly, but with a message about a key rather than about
    // the two files that caused it.
    throw new Error(
      `${ATHLETE_SOURCES} holds ${String(documents.length)} documents; the archive takes one.`,
    );
  }

  const openRows = (): AsyncIterable<string> =>
    createInterface({
      input: createReadStream(corpus, { encoding: 'utf8' }),
      // A row split across a chunk boundary otherwise arrives as two rows, both
      // of which project into nonsense that passes every check.
      crlfDelay: Number.POSITIVE_INFINITY,
    });

  const { mirror, info, freshness, withheld } = await buildAthleteMirror(document.value, openRows);

  let entryCount = 0;
  let bucketCount = 0;
  for (const shard of shardAthleteMirror(mirror.athletes, SCHEMA_VERSION)) {
    artifacts.push(shard);
    entryCount += shard.entryCount;
    bucketCount += 1;
  }

  // The one artifact that answers "is there an archive here at all", published
  // last of the group so it reads as the summary it is.
  artifacts.push({
    id: ATHLETE_MIRROR_ARTIFACT_ID,
    schema: AthleteMirrorInfoSchema,
    schemaVersion: SCHEMA_VERSION,
    value: info,
  });
  sources.push(freshness);

  // Counts and never a name (section 2.3). These four numbers are what a person
  // reading the build log needs: a mirror that halved, or a withheld count that
  // jumped, is upstream having changed something.
  console.log(
    `${document.path}: mirrored ${String(info.athleteCount)} lifters and ` +
      `${String(entryCount)} entries into ${String(bucketCount)} buckets, ` +
      `withheld ${String(withheld.length)} rows.`,
  );
  if (withheld.length > 0) {
    console.log(`  ${summarizeWithheld(withheld)}`);
  }
}

/**
 * Reads every JSON document in a directory, in filename order.
 *
 * Sorted because `readdir` is not, and the order reaches the index: two builds
 * of one commit that listed the sources differently would produce a different
 * `meta.json`, and the whole publishing design rests on identical inputs giving
 * identical bytes.
 */
async function readSourceDocuments(
  directory: string,
): Promise<readonly { path: string; value: unknown }[]> {
  const root = resolve(process.cwd(), directory);
  const names = (await readdir(root)).filter((name) => name.endsWith('.json')).sort();

  const documents = [];
  for (const name of names) {
    const path = join(directory, name);
    const contents = await readFile(join(root, name), 'utf8');
    try {
      documents.push({ path, value: JSON.parse(contents) as unknown });
    } catch (cause) {
      // Rethrown with the filename. `JSON.parse` reports a position in a string
      // it does not name, which in a directory of similar documents identifies
      // nothing.
      throw new Error(`${path}: is not valid JSON.`, { cause });
    }
  }
  return documents;
}

/**
 * Reads a committed upstream dataset and digests the bytes on disk.
 *
 * The digest is taken here, from the file, and compared inside the adapter
 * against the value the mapping declares. Computing it anywhere closer to the
 * comparison would make it possible to digest the parsed value instead, which
 * would agree with itself no matter what the file said.
 *
 * The filename came from the document, so it is joined rather than resolved and
 * the adapter has already refused anything containing a path separator.
 */
async function readSnapshot(
  directory: string,
  file: string,
): Promise<{ value: unknown; sha256: string }> {
  const path = join(directory, file);
  const bytes = await readFile(resolve(process.cwd(), path));
  try {
    return {
      value: JSON.parse(bytes.toString('utf8')) as unknown,
      sha256: createHash('sha256').update(bytes).digest('hex'),
    };
  } catch (cause) {
    throw new Error(`${path}: is not valid JSON.`, { cause });
  }
}

/**
 * Reads a committed crawl, with no digest taken.
 *
 * The omission is the point and is not an oversight: record tables change after
 * every meet weekend and refresh with nobody watching, so a pinned digest would
 * either be re-cut by the same job that changed the file -- which is not a
 * review -- or stop the refresh dead. The adapter checks meaning instead, and
 * the header of `sources/records.ts` says how.
 *
 * The filename came from the document, so it is joined rather than resolved and
 * the adapter has already refused anything containing a path separator.
 */
async function readRecordSnapshot(directory: string, file: string): Promise<unknown> {
  const path = join(directory, file);
  const contents = await readFile(resolve(process.cwd(), path), 'utf8');
  try {
    return JSON.parse(contents) as unknown;
  } catch (cause) {
    throw new Error(`${path}: is not valid JSON.`, { cause });
  }
}

/**
 * Empties the output directory, after checking it is the one we think it is.
 *
 * A missing directory is the normal case on a clean checkout and is not an
 * error. An unexpected entry is: this function deletes, and the cost of being
 * pointed at the wrong path once is somebody's working tree.
 */
async function clearOutputDirectory(directory: string): Promise<void> {
  let entries: readonly string[];
  try {
    entries = await readdir(directory);
  } catch (error) {
    if (error instanceof Error && 'code' in error && error.code === 'ENOENT') {
      return;
    }
    throw error;
  }

  const unexpected = entries.filter((entry) => !EXPECTED_OUTPUT_ENTRIES.has(entry));
  if (unexpected.length > 0) {
    throw new Error(
      `Refusing to clear ${directory}: it holds ${unexpected.join(', ')}, which this ` +
        'script did not write. Check the output path before deleting anything.',
    );
  }

  await rm(directory, { recursive: true, force: true });
}

/**
 * The build timestamp, from the environment rather than the clock.
 *
 * `planPublication` is pure so that one commit always publishes the same bytes;
 * reading the clock here would undo that for the one field it cannot compute.
 * CI passes the commit's own timestamp, which makes a rebuild of an old commit
 * checkable against what was published from it. A developer running a local
 * build gets the clock and a note saying so, because reproducibility is a
 * property of the release, not of every build on every machine.
 */
function readGeneratedAt(): string {
  const supplied = process.env['PTK_GENERATED_AT'];
  if (supplied === undefined || supplied === '') {
    const now = new Date().toISOString();
    console.log(`PTK_GENERATED_AT is unset; stamping this build with the clock (${now}).`);
    return now;
  }
  if (Number.isNaN(Date.parse(supplied))) {
    throw new Error(`PTK_GENERATED_AT is not a timestamp: ${JSON.stringify(supplied)}`);
  }
  return supplied;
}

await main();
